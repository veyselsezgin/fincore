export interface NpvBookInput {
  rate: number;
  cashFlows: number[];
  firstPeriod: 0 | 1;
  sensitivity?: E.NpvSensitivityOutput | null;
}

export function npvBook({ rate, cashFlows, firstPeriod, sensitivity }: NpvBookInput): XBook {
  const n = cashFlows.length;
  const first = 7;
  const last = first + n - 1;
  const npv = E.npvRaw(rate, cashFlows, firstPeriod);
  const irr = E.irr({ cashFlows });

  const rows: XCell[][] = [
    title('FinCore: Net present value'),
    note(ENGINE_NOTE),
    ['Discount rate', pct(rate)],
    ['First cash flow at', firstPeriod === 0 ? 't = 0 (today)' : 't = 1 (Excel NPV convention)'],
    [],
    header('Period', 'Cash flow', 'Discount period', 'Present value'),
  ];
  cashFlows.forEach((cf, i) => {
    const r = first + i;
    rows.push([
      { v: i, fmt: 'int' },
      money(cf),
      { v: i + firstPeriod, fmt: 'int' },
      { f: `B${r}/(1+$B$3)^C${r}`, v: cf / (1 + rate) ** (i + firstPeriod), fmt: 'money' },
    ]);
  });
  rows.push([]);
  rows.push([
    'NPV',
    { f: npvFormula('$B$3', first, last, 'B', firstPeriod), v: npv, fmt: 'money', bold: true },
  ]);
  rows.push([
    'Sum of present values (check)',
    { f: `SUM(D${first}:D${last})`, v: npv, fmt: 'money' },
  ]);
  if (irr.value?.irr != null) {
    rows.push(['IRR', { f: `IRR(B${first}:B${last})`, v: irr.value.irr, fmt: 'pct' }]);
  } else if (irr.value) {
    rows.push([
      'IRR',
      `Several IRRs (${irr.value.roots.map((x) => (x * 100).toFixed(2) + '%').join(', ')}); see the IRR export.`,
    ]);
  } else {
    rows.push(['IRR', irr.errors[0]?.message ?? 'Not available']);
  }

  const book: XBook = {
    fileName: 'fincore-npv.xlsx',
    sheets: [{ name: 'NPV', rows, widths: [30, 16, 16, 16] }],
  };

  if (sensitivity) {
    const ref = sheetRef('NPV');
    const s: XCell[][] = [
      title('NPV sensitivity: cash flows (rows) × discount rate (columns)'),
      note(
        'Rows scale every cash flow after the first; columns scale the rate relatively (+20% on 10% = 12%).',
      ),
      [{ t: 'Rate shock →', bold: true }, ...sensitivity.rateShocks.map((x) => pct(x))],
      [
        { t: 'Discount rate', bold: true },
        ...sensitivity.rateShocks.map((_, j) => ({
          f: `${ref}$B$3*(1+${col(j + 1)}3)`,
          v: sensitivity.rates[j]!,
          fmt: 'pct' as const,
        })),
      ],
      [{ t: 'Cash-flow shock ↓', bold: true }],
    ];
    sensitivity.cashFlowShocks.forEach((shock, i) => {
      const r = 6 + i;
      const cells: XCell[] = [pct(shock)];
      sensitivity.rateShocks.forEach((_, j) => {
        const c = `${col(j + 1)}$4`;
        const rest =
          n > 1
            ? `+(1+$A${r})*SUMPRODUCT(${ref}$B$${first + 1}:$B$${last}/(1+${c})^${ref}$C$${first + 1}:$C$${last})`
            : '';
        cells.push({
          f: `${ref}$B$${first}/(1+${c})^${ref}$C$${first}${rest}`,
          v: sensitivity.npv[i]![j]!,
          fmt: 'money',
        });
      });
      s.push(cells);
    });
    book.sheets.push({
      name: 'Sensitivity',
      rows: s,
      widths: [20, ...sensitivity.rateShocks.map(() => 14)],
    });
  }
  return book;
}

