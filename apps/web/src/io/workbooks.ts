export type SolveFor = 'fv' | 'pv' | 'pmt' | 'nper' | 'rate';

export interface TvmBookInput {
  solveFor: SolveFor;
  annualRate: number;
  ppy: number;
  nper: number;
  pv: number;
  pmt: number;
  fv: number;
  timing: E.PaymentTiming;
  result: number | null;
}

export function tvmBook(i: TvmBookInput): XBook {
  const known = (key: SolveFor, label: string, v: number, fmt: 'money' | 'pct' | 'num'): XCell[] =>
    i.solveFor === key ? [label, '(solved below)'] : [label, { v, fmt }];
  const rows: XCell[][] = [
    title('FinCore: Time value of money'),
    note(ENGINE_NOTE),
    known('rate', 'Annual rate', i.annualRate, 'pct'), // B3
    ['Periods per year', { v: i.ppy, fmt: 'int' }], // B4
    known('nper', 'Number of periods', i.nper, 'num'), // B5
    known('pv', 'Present value', i.pv, 'money'), // B6
    known('pmt', 'Payment', i.pmt, 'money'), // B7
    known('fv', 'Future value', i.fv, 'money'), // B8
    ['Type (0 = end, 1 = beginning)', { v: i.timing === 'begin' ? 1 : 0, fmt: 'int' }], // B9
    [
      'Rate per period',
      i.solveFor === 'rate'
        ? '(solved below)'
        : { f: 'B3/B4', v: i.annualRate / i.ppy, fmt: 'pct' },
    ], // B10
    [],
  ];
  const v = i.result;
  switch (i.solveFor) {
    case 'fv':
      rows.push(['Future value', { f: 'FV(B10,B5,B7,B6,B9)', v, fmt: 'money', bold: true }]);
      break;
    case 'pv':
      rows.push(['Present value', { f: 'PV(B10,B5,B7,B8,B9)', v, fmt: 'money', bold: true }]);
      break;
    case 'pmt':
      rows.push(['Payment', { f: 'PMT(B10,B5,B6,B8,B9)', v, fmt: 'money', bold: true }]);
      break;
    case 'nper':
      rows.push(['Number of periods', { f: 'NPER(B10,B7,B6,B8,B9)', v, fmt: 'num', bold: true }]);
      break;
    case 'rate':
      rows.push(['Rate per period', { f: 'RATE(B5,B7,B6,B8,B9)', v, fmt: 'pct', bold: true }]);
      rows.push([
        'Nominal annual rate',
        { f: 'B12*B4', v: v === null ? null : v * i.ppy, fmt: 'pct' },
      ]);
      break;
  }
  return { fileName: 'fincore-tvm.xlsx', sheets: [{ name: 'TVM', rows, widths: [30, 18] }] };
}

export function amortizationBook(input: E.AmortizationInput, out: E.AmortizationOutput): XBook {
  const dp = E.CURRENCY_MINOR_UNITS[out.currency];
  const first = 12;
  const rows: XCell[][] = [
    title(`FinCore: Loan amortization (${out.currency})`),
    note(ENGINE_NOTE),
    ['Loan amount', money(Number(input.principal))], // B3
    ['Annual rate', pct(input.annualRate)], // B4
    ['Payments per year', { v: input.periodsPerYear, fmt: 'int' }], // B5
    ['Number of payments', { v: input.nper, fmt: 'int' }], // B6
    ['Rate per period', { f: 'B4/B5', v: input.annualRate / input.periodsPerYear, fmt: 'pct' }], // B7
    [
      'Regular payment',
      { f: `ROUND(-PMT(B7,B6,B3),${dp})`, v: Number(out.payment), fmt: 'money', bold: true },
    ], // B8
    [
      'Total interest',
      {
        f: `SUM(C${first}:C${first + out.rows.length - 1})`,
        v: Number(out.totalInterest),
        fmt: 'money',
      },
    ],
    note(`Interest is rounded to ${dp} decimals each period; the last payment clears the balance.`),
    header('Payment #', 'Opening balance', 'Interest', 'Payment', 'Principal', 'Closing balance'),
  ];
  out.rows.forEach((row, k) => {
    const r = first + k;
    rows.push([
      { v: row.period, fmt: 'int' },
      { f: k === 0 ? '$B$3' : `F${r - 1}`, v: Number(row.openingBalance), fmt: 'money' },
      { f: `ROUND(B${r}*$B$7,${dp})`, v: Number(row.interest), fmt: 'money' },
      {
        f: `IF(OR(A${r}=$B$6,$B$8-C${r}>B${r}),B${r}+C${r},$B$8)`,
        v: Number(row.payment),
        fmt: 'money',
      },
      { f: `D${r}-C${r}`, v: Number(row.principal), fmt: 'money' },
      { f: `ROUND(B${r}-E${r},${dp})`, v: Number(row.closingBalance), fmt: 'money' },
    ]);
  });
  return {
    fileName: 'fincore-amortization.xlsx',
    sheets: [{ name: 'Schedule', rows, widths: [22, 18, 14, 14, 14, 18] }],
  };
}

export function compareBook(
  rate: number,
  a: number[],
  b: number[],
  out: E.CompareProjectsOutput,
): XBook {
  const n = out.incremental.length;
  const first = 6;
  const last = first + n - 1;
  const pad = (xs: number[]) => [...xs, ...Array(n - xs.length).fill(0)] as number[];
  const A = pad(a);
  const B = pad(b);
  const rows: XCell[][] = [
    title('FinCore: Mutually exclusive projects'),
    note(ENGINE_NOTE),
    ['Discount rate', pct(rate)],
    [],
    header('Period', 'Project A', 'Project B', 'A − B (incremental)'),
  ];
  for (let i = 0; i < n; i++) {
    const r = first + i;
    rows.push([
      { v: i, fmt: 'int' },
      money(A[i]!),
      money(B[i]!),
      { f: `B${r}-C${r}`, v: out.incremental[i]!, fmt: 'money' },
    ]);
  }
  rows.push([]);
  rows.push([
    'NPV A',
    { f: npvFormula('$B$3', first, last, 'B', 0), v: out.npvA, fmt: 'money', bold: true },
  ]);
  rows.push([
    'NPV B',
    { f: npvFormula('$B$3', first, last, 'C', 0), v: out.npvB, fmt: 'money', bold: true },
  ]);
  rows.push([
    'IRR A',
    out.irrA === null ? 'No unique IRR' : { f: `IRR(B${first}:B${last})`, v: out.irrA, fmt: 'pct' },
  ]);
  rows.push([
    'IRR B',
    out.irrB === null ? 'No unique IRR' : { f: `IRR(C${first}:C${last})`, v: out.irrB, fmt: 'pct' },
  ]);
  if (out.crossoverRates.length === 0)
    rows.push(['Fisher crossover rate', 'None: the NPV profiles do not cross']);
  out.crossoverRates.forEach((x, k) =>
    rows.push([
      out.crossoverRates.length === 1 ? 'Fisher crossover rate' : `Fisher crossover rate ${k + 1}`,
      {
        f: `IRR(D${first}:D${last}${out.crossoverRates.length > 1 ? `,${x.toFixed(6)}` : ''})`,
        v: x,
        fmt: 'pct',
        bold: true,
      },
    ]),
  );
  rows.push(['Preferred by NPV', out.choiceByNpv]);
  rows.push(['Preferred by IRR', out.choiceByIrr]);
  return {
    fileName: 'fincore-compare.xlsx',
    sheets: [{ name: 'Compare', rows, widths: [24, 16, 16, 20] }],
  };
}

const DIST_LABEL: Record<E.Distribution['type'], string> = {
  fixed: 'Fixed',
  normal: 'Normal',
  triangular: 'Triangular',
  uniform: 'Uniform',
};

export function monteCarloBook(
  rate: E.Distribution,
  flows: E.Distribution[],
  out: E.MonteCarloNpvOutput,
): XBook {
  const params = (d: E.Distribution): XCell[] => {
    switch (d.type) {
      case 'fixed':
        return [money(d.value), null, null];
      case 'normal':
        return [money(d.mean), money(d.sd), null];
      case 'triangular':
        return [money(d.min), money(d.mode), money(d.max)];
      case 'uniform':
        return [money(d.min), money(d.max), null];
    }
  };
  const meanFormula = (d: E.Distribution, r: number) =>
    d.type === 'triangular'
      ? `(C${r}+D${r}+E${r})/3`
      : d.type === 'uniform'
        ? `(C${r}+D${r})/2`
        : `C${r}`;
  const first = 7;
  const last = first + flows.length - 1;
  const rows: XCell[][] = [
    title('FinCore: Monte Carlo NPV simulation'),
    note(ENGINE_NOTE),
    note(
      `Simulation results are values from ${out.iterations.toLocaleString('en-US')} iterations with seed ${out.seed}; rerun in FinCore with the same seed to reproduce them exactly.`,
    ),
    ['Discount rate (expected)', pct(E.distributionMean(rate))],
    [],
    header('Period', 'Distribution', 'Param 1', 'Param 2', 'Param 3', 'Expected value'),
  ];
  flows.forEach((d, i) => {
    const r = first + i;
    rows.push([
      { v: i, fmt: 'int' },
      DIST_LABEL[d.type],
      ...params(d),
      { f: meanFormula(d, r), v: E.distributionMean(d), fmt: 'money' },
    ]);
  });
  rows.push(
    note(
      'Param columns: Fixed = value; Normal = mean, SD; Triangular = min, most likely, max; Uniform = min, max.',
    ),
  );
  rows.push([]);
  rows.push([
    'NPV at expected values',
    { f: npvFormula('$B$4', first, last, 'F', 0), v: out.npvAtMeans, fmt: 'money', bold: true },
  ]);
  rows.push(['Probability NPV > 0', pct(out.probabilityPositive)]);
  rows.push(['Standard error of probability', pct(out.probabilityStdError)]);
  rows.push(['Mean NPV', money(out.mean)]);
  rows.push(['Standard deviation', money(out.sd)]);
  for (const p of out.percentiles) rows.push([`P${Math.round(p.p * 100)}`, money(p.value)]);
  rows.push([]);
  rows.push(header('Histogram: from', 'to', 'count'));
  for (const b of out.histogram) rows.push([money(b.x0), money(b.x1), { v: b.count, fmt: 'int' }]);
  return {
    fileName: 'fincore-monte-carlo.xlsx',
    sheets: [{ name: 'Monte Carlo', rows, widths: [30, 14, 14, 14, 14, 16] }],
  };
}

/**
 * 30/360 US (bond basis) written out explicitly. Excel's YEARFRAC(…, 0) deviates from this rule
 * when the start is the last day of February and the end is the 31st (it leaves the 31st alone),
 * so the export spells the rule out instead of relying on YEARFRAC.
 */
function thirty360UsFormula(s: string, e: string): string {
  const feb = (x: string) => `AND(MONTH(${x})=2,DAY(${x}+1)=1)`;
  const d1 = `IF(${feb(s)},30,MIN(DAY(${s}),30))`;
  const d2 = `IF(AND(${feb(s)},${feb(e)}),30,IF(AND(DAY(${e})=31,${d1}>=30),30,DAY(${e})))`;
  return `(360*(YEAR(${e})-YEAR(${s}))+30*(MONTH(${e})-MONTH(${s}))+${d2}-${d1})/360`;
}

export function dayCountBook(start: string, end: string): XBook {
  const yf = (dc: E.DayCount) =>
    E.yearFraction({ start, end, dayCount: dc }).value?.yearFraction ?? null;
  const rows: XCell[][] = [
    title('FinCore: Year fractions'),
    note(ENGINE_NOTE),
    ['Start date', { date: start }],
    ['End date', { date: end }],
    [],
    header('Convention', 'Year fraction', 'Note'),
    [
      '30/360-US',
      { f: thirty360UsFormula('$B$3', '$B$4'), v: yf('30/360-US'), fmt: 'num' },
      'Bond-basis rule written out; see the comparison row below',
    ],
    ['30E/360', { f: 'YEARFRAC($B$3,$B$4,4)', v: yf('30E/360'), fmt: 'num' }, 'Excel basis 4'],
    ['ACT/360', { f: 'YEARFRAC($B$3,$B$4,2)', v: yf('ACT/360'), fmt: 'num' }, 'Excel basis 2'],
    ['ACT/365F', { f: 'YEARFRAC($B$3,$B$4,3)', v: yf('ACT/365F'), fmt: 'num' }, 'Excel basis 3'],
    [
      'ACT/ACT-ISDA',
      { v: yf('ACT/ACT-ISDA') ?? 0, fmt: 'num' },
      'Value from FinCore: Excel basis 1 uses an average year length and differs across years',
    ],
    [],
    [
      'Excel YEARFRAC basis 0 (for comparison)',
      { f: 'YEARFRAC($B$3,$B$4,0)', fmt: 'num' },
      'Differs from 30/360-US when the start is the last day of February and the end is the 31st',
    ],
  ];
  return {
    fileName: 'fincore-daycount.xlsx',
    sheets: [{ name: 'Day count', rows, widths: [38, 16, 80] }],
  };
}
