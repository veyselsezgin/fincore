export function irrBook(cashFlows: number[]): XBook {
  const first = 5;
  const last = first + cashFlows.length - 1;
  const r = E.irr({ cashFlows });
  const rows: XCell[][] = [
    title('FinCore: Internal rate of return'),
    note(ENGINE_NOTE),
    [],
    header('Period', 'Cash flow'),
  ];
  cashFlows.forEach((cf, i) => rows.push([{ v: i, fmt: 'int' }, money(cf)]));
  rows.push([]);
  const roots = r.value?.roots ?? [];
  if (roots.length === 1) {
    rows.push(['IRR', { f: `IRR(B${first}:B${last})`, v: roots[0]!, fmt: 'pct', bold: true }]);
  } else if (roots.length > 1) {
    rows.push(
      note(
        `These cash flows have ${roots.length} IRRs. Excel's IRR returns the one nearest its guess, so each is shown with a guess.`,
      ),
    );
    roots.forEach((x, i) =>
      rows.push([
        `IRR ${i + 1}`,
        { f: `IRR(B${first}:B${last},${x.toFixed(6)})`, v: x, fmt: 'pct', bold: true },
      ]),
    );
  } else {
    rows.push(['IRR', r.errors[0]?.message ?? 'Not available']);
  }
  return { fileName: 'fincore-irr.xlsx', sheets: [{ name: 'IRR', rows, widths: [16, 16] }] };
}

export function mirrBook(cashFlows: number[], financeRate: number, reinvestRate: number): XBook {
  const first = 7;
  const last = first + cashFlows.length - 1;
  const m = E.mirr({ cashFlows, financeRate, reinvestRate });
  const rows: XCell[][] = [
    title('FinCore: Modified IRR'),
    note(ENGINE_NOTE),
    ['Finance rate', pct(financeRate)],
    ['Reinvestment rate', pct(reinvestRate)],
    [],
    header('Period', 'Cash flow'),
  ];
  cashFlows.forEach((cf, i) => rows.push([{ v: i, fmt: 'int' }, money(cf)]));
  rows.push([]);
  rows.push(['MIRR', { f: `MIRR(B${first}:B${last},B3,B4)`, v: m.value, fmt: 'pct', bold: true }]);
  return { fileName: 'fincore-mirr.xlsx', sheets: [{ name: 'MIRR', rows, widths: [20, 16] }] };
}

export function xirrBook(rate: number, flows: E.DatedCashFlow[]): XBook {
  const first = 6;
  const last = first + flows.length - 1;
  const x = E.xnpv({ rate, flows });
  const i = E.xirr({ flows });
  const rows: XCell[][] = [
    title('FinCore: Dated cash flows'),
    note(ENGINE_NOTE),
    ['Annual discount rate', pct(rate)],
    [],
    header('Date', 'Amount'),
  ];
  flows.forEach((f) => rows.push([{ date: f.date }, money(f.amount)]));
  rows.push([]);
  rows.push([
    'XNPV',
    { f: `XNPV(B3,B${first}:B${last},A${first}:A${last})`, v: x.value, fmt: 'money', bold: true },
  ]);
  if (i.value?.xirr != null) {
    rows.push([
      'XIRR',
      { f: `XIRR(B${first}:B${last},A${first}:A${last})`, v: i.value.xirr, fmt: 'pct', bold: true },
    ]);
  } else {
    rows.push([
      'XIRR',
      i.value ? 'Several solutions; see FinCore' : (i.errors[0]?.message ?? 'Not available'),
    ]);
  }
  return { fileName: 'fincore-xirr.xlsx', sheets: [{ name: 'XIRR', rows, widths: [22, 16] }] };
}

