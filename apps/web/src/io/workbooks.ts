import * as E from '@fincore/engine';
import { col, sheetRef, type XBook, type XCell } from './xlsx';

/**
 * Excel workbooks with live formulas for each calculator. Every formula cell also carries the
 * engine's value as its cached result, so the file shows numbers even before Excel recalculates.
 * Labels in column A are stable: tests look formulas up by them.
 */

const title = (t: string): XCell[] => [{ t, bold: true }];
const header = (...cols: string[]): XCell[] => cols.map((t) => ({ t, bold: true }));
const note = (t: string): XCell[] => [{ t, italic: true }];
const money = (v: number): XCell => ({ v, fmt: 'money' });
const pct = (v: number): XCell => ({ v, fmt: 'pct' });
const ENGINE_NOTE = `Generated by FinCore engine v${E.ENGINE_VERSION}. Inputs are editable; formulas recalculate in Excel.`;

/** Excel formula for NPV with FinCore's t = 0 convention: CF0 + NPV(r, CF1..CFn). */
function npvFormula(
  rateRef: string,
  firstRow: number,
  lastRow: number,
  column: string,
  firstPeriod: 0 | 1,
): string {
  if (firstPeriod === 1) return `NPV(${rateRef},${column}${firstRow}:${column}${lastRow})`;
  if (lastRow === firstRow) return `${column}${firstRow}`;
  return `${column}${firstRow}+NPV(${rateRef},${column}${firstRow + 1}:${column}${lastRow})`;
}

