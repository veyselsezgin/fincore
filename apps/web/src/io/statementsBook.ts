import * as E from '@fincore/engine';
import { col, sheetRef, type Fmt, type XBook, type XCell } from './xlsx';

/**
 * Financial statement analysis as a live Excel model: inputs on "Statements", every ratio,
 * DuPont factor, Altman component and the what-if as formulas referencing those cells.
 * Cached values come from the engine; tests evaluate every formula against them.
 */

const ST = 'Statements';
const S = sheetRef(ST);
const FIRST_ITEM_ROW = 7;

const UNIT_FMT: Record<E.RatioUnit, Fmt> = { x: 'ratio', pct: 'pct', days: 'days', money: 'money' };

export function statementsBook(input: E.StatementAnalysisInput, out: E.StatementAnalysis): XBook {
  const n = input.periods.length;
  const days = input.daysInYear ?? 365;
  const pc = (p: number) => col(p + 1); // period column on every sheet: B, C, D

  // --- Statements sheet: inputs + derived lines ------------------------------------------------
  const rowOf = {} as Record<E.StatementItemKey, number>;
  const rows: XCell[][] = [
    [{ t: 'FinCore: Financial statements', bold: true }],
    [
      {
        t: `Generated by FinCore engine v${E.ENGINE_VERSION}. Edit the blue input rows; everything else recalculates.`,
        italic: true,
      },
    ],
    ['Days in year', { v: days, fmt: 'int' }], // B3
    [
      'Statutory tax rate (for ROIC when EBT ≤ 0)',
      input.statutoryTaxRate === undefined ? null : { v: input.statutoryTaxRate, fmt: 'pct' },
    ], // B4
    [],
    [{ t: 'Line item', bold: true }, ...out.periods.map((p) => ({ t: p, bold: true }))],
  ];
  E.STATEMENT_ITEMS.forEach((it, k) => {
    const r = FIRST_ITEM_ROW + k;
    rowOf[it.key] = r;
    rows.push([
      it.label,
      ...input.periods.map((p) => {
        const v = p[it.key];
        return v === null ? null : ({ v, fmt: 'money' } as XCell);
      }),
    ]);
  });
  rows.push([]);
  const ref = (key: E.StatementItemKey, p: number, sheet = '') => `${sheet}${pc(p)}${rowOf[key]}`;

  type DKey = Exclude<keyof E.DerivedLines, 'taxRateUsed'> | 'taxRateUsed';
  const dRow = {} as Record<DKey, number>;
  const derivedSpec: [DKey, string, (p: number) => string, Fmt][] = [
    [
      'currentAssets',
      'Current assets',
      (p) => `SUM(${ref('cash', p)}:${ref('otherCurrentAssets', p)})`,
      'money',
    ],
    [
      'totalAssets',
      'Total assets',
      (p) => `${pc(p)}${dRow.currentAssets}+${ref('nonCurrentAssets', p)}`,
      'money',
    ],
    [
      'currentLiabilities',
      'Current liabilities',
      (p) => `SUM(${ref('payables', p)}:${ref('otherCurrentLiabilities', p)})`,
      'money',
    ],
    [
      'totalLiabilities',
      'Total liabilities',
      (p) =>
        `${pc(p)}${dRow.currentLiabilities}+${ref('longTermDebt', p)}+${ref('otherNonCurrentLiabilities', p)}`,
      'money',
    ],
    [
      'totalDebt',
      'Total debt',
      (p) => `${ref('shortTermDebt', p)}+${ref('longTermDebt', p)}`,
      'money',
    ],
    [
      'liabilitiesAndEquity',
      'Liabilities + equity',
      (p) => `${pc(p)}${dRow.totalLiabilities}+${ref('equity', p)}`,
      'money',
    ],
    [
      'balanceDifference',
      'Balance check (assets − L&E, should be 0)',
      (p) => `${pc(p)}${dRow.totalAssets}-${pc(p)}${dRow.liabilitiesAndEquity}`,
      'money',
    ],
    ['grossProfit', 'Gross profit', (p) => `${ref('revenue', p)}-${ref('cogs', p)}`, 'money'],
    [
      'ebitda',
      'EBITDA',
      (p) => `${pc(p)}${dRow.grossProfit}-${ref('operatingExpenses', p)}`,
      'money',
    ],
    ['ebit', 'EBIT', (p) => `${pc(p)}${dRow.ebitda}-${ref('depreciation', p)}`, 'money'],
    [
      'ebt',
      'Profit before tax (EBT)',
      (p) => `${pc(p)}${dRow.ebit}-${ref('interestExpense', p)}+${ref('otherIncome', p)}`,
      'money',
    ],
    ['netIncome', 'Net income', (p) => `${pc(p)}${dRow.ebt}-${ref('taxExpense', p)}`, 'money'],
    [
      'taxRateUsed',
      'Tax rate used for NOPAT',
      (p) => {
        const ebt = `${pc(p)}${dRow.ebt}`;
        const eff = `${ref('taxExpense', p)}/${ebt}`;
        const stat = input.statutoryTaxRate === undefined ? '"n/a"' : '$B$4';
        return `IF(${ebt}>0,IF(AND(${eff}>=0,${eff}<1),${eff},${stat}),${stat})`;
      },
      'pct',
    ],
  ];
  rows.push([{ t: 'Derived lines', bold: true }]);
  for (const [key, label, f, fmt] of derivedSpec) {
    dRow[key] = rows.length + 1;
    rows.push([label, ...out.derived.map((d, p) => ({ f: f(p), v: d[key], fmt }) as XCell)]);
  }
  const D = (key: DKey, p: number, sheet = S) => `${sheet}${pc(p)}${dRow[key]}`;

  // --- Ratios sheet ------------------------------------------------------------------------------
  const avgS = (key: E.StatementItemKey, p: number) =>
    p === 0 ? ref(key, 0, S) : `AVERAGE(${ref(key, p - 1, S)},${ref(key, p, S)})`;
  const avgD = (key: DKey, p: number) =>
    p === 0 ? D(key, 0) : `AVERAGE(${D(key, p - 1)},${D(key, p)})`;
  const s = (key: E.StatementItemKey, p: number) => ref(key, p, S);
  const ratioRow: Partial<Record<E.RatioId, number>> = {};
  const R = (id: E.RatioId, p: number) => `${pc(p)}${ratioRow[id]}`;
  const iferr = (x: string) => `IFERROR(${x},"n/a")`;
  const daysRef = `${S}$B$3`;

  const formulas: Record<E.RatioId, (p: number) => string> = {
    currentRatio: (p) => iferr(`${D('currentAssets', p)}/${D('currentLiabilities', p)}`),
    quickRatio: (p) =>
      iferr(
        `(${s('cash', p)}+${s('shortTermInvestments', p)}+${s('receivables', p)})/${D('currentLiabilities', p)}`,
      ),
    cashRatio: (p) =>
      iferr(`(${s('cash', p)}+${s('shortTermInvestments', p)})/${D('currentLiabilities', p)}`),
    netWorkingCapital: (p) => `${D('currentAssets', p)}-${D('currentLiabilities', p)}`,
    inventoryTurnover: (p) => iferr(`${s('cogs', p)}/${avgS('inventory', p)}`),
    dio: (p) => iferr(`${avgS('inventory', p)}/${s('cogs', p)}*${daysRef}`),
    dso: (p) => iferr(`${avgS('receivables', p)}/${s('revenue', p)}*${daysRef}`),
    dpo: (p) => iferr(`${avgS('payables', p)}/${s('cogs', p)}*${daysRef}`),
    assetTurnover: (p) => iferr(`${s('revenue', p)}/${avgD('totalAssets', p)}`),
    ccc: (p) => iferr(`${R('dio', p)}+${R('dso', p)}-${R('dpo', p)}`),
    debtToAssets: (p) => iferr(`${D('totalDebt', p)}/${D('totalAssets', p)}`),
    debtToEquity: (p) => `IF(${s('equity', p)}>0,${D('totalDebt', p)}/${s('equity', p)},"n/a")`,
    interestCoverage: (p) => iferr(`${D('ebit', p)}/${s('interestExpense', p)}`),
    dscr: (p) =>
      iferr(`${D('ebitda', p)}/(${s('interestExpense', p)}+${s('principalRepayment', p)})`),
    grossMargin: (p) => iferr(`${D('grossProfit', p)}/${s('revenue', p)}`),
    ebitdaMargin: (p) => iferr(`${D('ebitda', p)}/${s('revenue', p)}`),
    netMargin: (p) => iferr(`${D('netIncome', p)}/${s('revenue', p)}`),
    roa: (p) => iferr(`${D('netIncome', p)}/${avgD('totalAssets', p)}`),
    roe: (p) => `IF(${avgS('equity', p)}>0,${D('netIncome', p)}/${avgS('equity', p)},"n/a")`,
    roic: (p) => {
      const ic = (q: number) => `(${D('totalDebt', q)}+${s('equity', q)})`;
      const avgIc = p === 0 ? ic(0) : `(${ic(p - 1)}+${ic(p)})/2`;
      return `IFERROR(IF(${avgIc}>0,${D('ebit', p)}*(1-${D('taxRateUsed', p)})/(${avgIc}),"n/a"),"n/a")`;
    },
  };

  const ratioRows: XCell[][] = [
    [{ t: 'FinCore: Ratios', bold: true }],
    [
      {
        t: 'Turnover, days and return ratios use average balances when the prior period exists.',
        italic: true,
      },
    ],
    [
      { t: 'Ratio', bold: true },
      ...out.periods.map((p) => ({ t: p, bold: true })),
      { t: 'Benchmark', bold: true },
      { t: 'Formula', bold: true },
    ],
  ];
  // CCC references DIO/DSO/DPO rows, so assign row numbers first.
  let category = '';
  const layout: (E.RatioRow | string)[] = [];
  for (const row of out.ratios) {
    if (row.category !== category) {
      category = row.category;
      layout.push(category);
    }
    layout.push(row);
  }
  layout.forEach((item, k) => {
    if (typeof item !== 'string') ratioRow[item.id] = 4 + k;
  });
  for (const item of layout) {
    if (typeof item === 'string') {
      ratioRows.push([{ t: item[0]!.toUpperCase() + item.slice(1), bold: true }]);
      continue;
    }
    const fmt = UNIT_FMT[item.unit];
    ratioRows.push([
      item.label,
      ...item.values.map((v, p) => ({ f: formulas[item.id](p), v, fmt }) as XCell),
      item.benchmark === null ? null : { v: item.benchmark, fmt },
      item.formula,
    ]);
  }
  const RA = sheetRef('Ratios');

  // --- DuPont sheet ------------------------------------------------------------------------------
  const avgEq = (p: number) => avgS('equity', p);
  const dupRows: XCell[][] = [
    [{ t: 'FinCore: DuPont analysis', bold: true }],
    [],
    [{ t: 'Factor', bold: true }, ...out.periods.map((p) => ({ t: p, bold: true }))],
  ];
  const dupSpec: [string, keyof E.DupontPeriod | 'roe3' | 'roe5', (p: number) => string, Fmt][] = [
    ['Net profit margin', 'netMargin', (p) => `${RA}${R('netMargin', p)}`, 'pct'],
    ['Asset turnover', 'assetTurnover', (p) => `${RA}${R('assetTurnover', p)}`, 'ratio'],
    [
      'Equity multiplier (avg assets / avg equity)',
      'equityMultiplier',
      (p) => `IF(${avgEq(p)}>0,${avgD('totalAssets', p)}/${avgEq(p)},"n/a")`,
      'ratio',
    ],
    ['ROE, 3-step (NM × AT × EM)', 'roe3', () => '', 'pct'], // product built below
    [
      'Tax burden (NI / EBT)',
      'taxBurden',
      (p) => iferr(`${D('netIncome', p)}/${D('ebt', p)}`),
      'ratio',
    ],
    [
      'Interest burden (EBT / EBIT)',
      'interestBurden',
      (p) => iferr(`${D('ebt', p)}/${D('ebit', p)}`),
      'ratio',
    ],
    ['EBIT margin', 'ebitMargin', (p) => iferr(`${D('ebit', p)}/${s('revenue', p)}`), 'pct'],
    ['ROE, 5-step (TB × IB × EBIT margin × AT × EM)', 'roe5', () => '', 'pct'], // product built below
  ];
  const dupRowOf: Record<string, number> = {};
  dupSpec.forEach(([, key], k) => (dupRowOf[key] = 4 + k));
  for (const [label, key, f, fmt] of dupSpec) {
    dupRows.push([
      label,
      ...out.dupont.map((d, p) => {
        const c = pc(p);
        let formula = f(p);
        let v: number | null;
        if (key === 'roe3') {
          formula = iferr(
            `${c}${dupRowOf.netMargin}*${c}${dupRowOf.assetTurnover}*${c}${dupRowOf.equityMultiplier}`,
          );
          v = d.roe;
        } else if (key === 'roe5') {
          formula = iferr(
            `${c}${dupRowOf.taxBurden}*${c}${dupRowOf.interestBurden}*${c}${dupRowOf.ebitMargin}*${c}${dupRowOf.assetTurnover}*${c}${dupRowOf.equityMultiplier}`,
          );
          v = d.taxBurden === null || d.interestBurden === null ? null : d.roe;
        } else {
          v = d[key];
        }
        return { f: formula, v, fmt } as XCell;
      }),
    ]);
  }

  // --- Altman sheet ------------------------------------------------------------------------------
  const model = input.altmanModel ?? 'private';
  const am = E.ALTMAN_MODELS[model];
  const altRows: XCell[][] = [
    [{ t: `FinCore: Altman ${am.label}`, bold: true }],
    [
      {
        t: `${am.source}. Distress below ${am.distress}, safe above ${am.safe}. Ending balances.`,
        italic: true,
      },
    ],
    [
      { t: 'Component', bold: true },
      ...out.periods.map((p) => ({ t: p, bold: true })),
      { t: 'Weight', bold: true },
    ],
  ];
  const xFormula = [
    (p: number) => `${D('currentAssets', p)}-${D('currentLiabilities', p)}`,
    (p: number) => s('retainedEarnings', p),
    (p: number) => D('ebit', p),
    (p: number) => (model === 'public' ? s('marketCap', p) : s('equity', p)),
    (p: number) => s('revenue', p),
  ];
  const xDen = [
    (p: number) => D('totalAssets', p),
    (p: number) => D('totalAssets', p),
    (p: number) => D('totalAssets', p),
    (p: number) => D('totalLiabilities', p),
    (p: number) => D('totalAssets', p),
  ];
  const weightRow0 = 4;
  am.weights.forEach((w, k) => {
    altRows.push([
      `X${k + 1}: ${out.altman[0]!.components[k]!.label}`,
      ...out.altman.map((a, p) => {
        const missing = model === 'public' && k === 3 && input.periods[p]!.marketCap === null;
        return (
          missing
            ? 'enter market value of equity'
            : {
                f: iferr(`(${xFormula[k]!(p)})/${xDen[k]!(p)}`),
                v: a.components[k]!.value,
                fmt: 'num',
              }
        ) as XCell;
      }),
      { v: w, fmt: 'num' },
    ]);
  });
  const wCol = col(n + 1);
  const zRow = altRows.length + 1;
  altRows.push([
    { t: 'Z-score', bold: true },
    ...out.altman.map(
      (a, p) =>
        ({
          f: iferr(
            am.weights
              .map((_, k) => `$${wCol}$${weightRow0 + k}*${pc(p)}${weightRow0 + k}`)
              .join('+'),
          ),
          v: a.score,
          fmt: 'num',
          bold: true,
        }) as XCell,
    ),
  ]);
  altRows.push([
    'Zone',
    ...out.altman.map(
      (a, p) =>
        ({
          f: `IFERROR(IF(${pc(p)}${zRow}<${am.distress},"Distress",IF(${pc(p)}${zRow}>${am.safe},"Safe","Grey")),"n/a")`,
          v: a.zone === null ? null : a.zone[0]!.toUpperCase() + a.zone.slice(1),
        }) as XCell,
    ),
  ]);

  const book: XBook = {
    fileName: 'fincore-statement-analysis.xlsx',
    sheets: [
      { name: ST, rows, widths: [44, 16, 16, 16] },
      { name: 'Ratios', rows: ratioRows, widths: [36, 14, 14, 14, 12, 60] },
      { name: 'DuPont', rows: dupRows, widths: [48, 14, 14, 14] },
      { name: 'Altman', rows: altRows, widths: [52, 14, 14, 14, 10] },
    ],
  };

  // --- What-if sheet -----------------------------------------------------------------------------
  if (input.whatIf && out.whatIf) {
    const last = n - 1;
    const w = out.whatIf;
    book.sheets.push({
      name: 'What-if',
      widths: [40, 16],
      rows: [
        [{ t: `FinCore: Working-capital what-if (${out.periods[last]})`, bold: true }],
        [
          {
            t: 'Negative days = faster collection / leaner inventory; positive DPO = paying suppliers later.',
            italic: true,
          },
        ],
        ['Change in DSO (days)', { v: input.whatIf.deltaDso, fmt: 'num' }], // B3
        ['Change in DIO (days)', { v: input.whatIf.deltaDio, fmt: 'num' }], // B4
        ['Change in DPO (days)', { v: input.whatIf.deltaDpo, fmt: 'num' }], // B5
        [],
        [
          'Cash from receivables',
          { f: `-B3*${s('revenue', last)}/${daysRef}`, v: w.cashFromReceivables, fmt: 'money' },
        ],
        [
          'Cash from inventory',
          { f: `-B4*${s('cogs', last)}/${daysRef}`, v: w.cashFromInventory, fmt: 'money' },
        ],
        [
          'Cash from payables',
          { f: `B5*${s('cogs', last)}/${daysRef}`, v: w.cashFromPayables, fmt: 'money' },
        ],
        [
          'Total cash released',
          { f: 'SUM(B7:B9)', v: w.totalCashReleased, fmt: 'money', bold: true },
        ],
        ['Current CCC (days)', { f: `${RA}${R('ccc', last)}`, v: w.currentCcc, fmt: 'days' }],
        [
          'New CCC (days)',
          { f: `IFERROR(B11+B4+B3-B5,"n/a")`, v: w.newCcc, fmt: 'days', bold: true },
        ],
      ],
    });
  }
  return book;
}
